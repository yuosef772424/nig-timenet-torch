"""Generate docs/MAP.md, the navigation page of the package (rule B7).

    python -m tests.build_map           write docs/MAP.md
    python -m tests.build_map --check   exit 1 when the file is stale

Deterministic (sorted, no line counts, no timestamps): it changes only when a title, card, registration or entry
point changes. Modules are parsed with ``ast``; only the registries table imports the package.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

from tests.cards import PKG_REL, ROOT, TITLE_MAX, card_problems, module_docstring, module_files, parse_card, title_of

MAP_REL = "docs/MAP.md"
PKG = "nig_timenet_torch"
HEADER = """# MAP — where do I edit X?

Generated by `python -m tests.build_map` (checked by `tests/test_cards.py::test_map_is_fresh`): do not edit.
Navigate: this page -> the module's card (`PURPOSE` / `TAGS` / `PITFALLS`, rule B7) -> the symbol (grep, then read by
line range). A module without a card shows its first docstring line; it gets a card when a PR next changes it.
"""


def _cell(s: str) -> str:
    return " ".join(s.split()).replace("|", "\\|")


def _row(rel: str, pkg_dir: Path) -> tuple[str, str, str]:
    doc = module_docstring((pkg_dir / rel).read_text(encoding="utf-8"))
    card = parse_card(doc)
    if card and not card_problems(card):
        what, tags = card["PURPOSE"], card["TAGS"]
    else:
        what, tags = title_of(doc) or ((doc or "").strip().splitlines() or [""])[0], ""
    return rel, _cell(what[: max(TITLE_MAX, 240)]), _cell(tags)


def modules_section(pkg_dir: Path) -> str:
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for rel in module_files(pkg_dir):
        top = rel.split("/")[0] if "/" in rel else "(package root)"
        groups.setdefault(top, []).append(_row(rel, pkg_dir))
    out = ["## Modules (`src/nig_timenet_torch/`)", ""]
    for top in sorted(groups):
        out += [f"### {top}", "", "| module | what it is for | tags |", "|---|---|---|"]
        out += [f"| `{rel}` | {what} | {tags} |" for rel, what, tags in groups[top]]
        out.append("")
    return "\n".join(out)


def registry_definitions(pkg_dir: Path) -> list[tuple[str, str]]:
    """(module relative path, variable) for every module-level ``NAME = Registry(...)``."""
    found = []
    for rel in module_files(pkg_dir):
        for node in ast.parse((pkg_dir / rel).read_text(encoding="utf-8")).body:
            if (isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)
                    and getattr(node.value.func, "id", getattr(node.value.func, "attr", "")) == "Registry"
                    and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)):
                found.append((rel, node.targets[0].id))
    return found


def registries_section(pkg_dir: Path) -> str:
    import importlib

    out = ["## Registries (`core/registry.py`; add a component = one file + one registration line)", "",
           "| kind | variable | module | registered names |", "|---|---|---|---|"]
    rows = []
    for rel, var in registry_definitions(pkg_dir):
        mod = importlib.import_module(f"{PKG}.{rel[:-3].replace('/', '.')}")
        reg = getattr(mod, var)
        rows.append((reg.kind, var, rel, ", ".join(f"`{n}`" for n in sorted(reg.names()))))
    out += [f"| {k} | `{v}` | `{m}` | {n} |" for k, v, m, n in sorted(rows)]
    return "\n".join(out) + "\n"


def entry_points_section(pkg_dir: Path) -> str:
    out = ["## Entry points", ""]
    for rel in module_files(pkg_dir):
        if rel.startswith("jobs/"):
            out.append(f"- `{rel}`: job entry (`docs/jobs/*.json` name it)")
        elif rel.endswith("__main__.py") or "__main__" in _main_guard(pkg_dir / rel):
            mod = rel[:-3].replace("/", ".").removesuffix(".__main__")
            out.append(f"- `{rel}`: runnable (`python -m {PKG}.{mod}`)")
    for nb in sorted((ROOT / "notebooks").glob("*.ipynb")):
        out.append(f"- `notebooks/{nb.name}`: notebook runner")
    return "\n".join(out) + "\n"


def _main_guard(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    return '"__main__"' if 'if __name__ == "__main__"' in text else ""


def build(pkg_dir: Path | None = None) -> str:
    pkg_dir = pkg_dir or ROOT / PKG_REL
    return "\n".join([HEADER, modules_section(pkg_dir), registries_section(pkg_dir), entry_points_section(pkg_dir)])


def main(argv: list[str]) -> int:
    path = ROOT / MAP_REL
    text = build()
    if "--check" in argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"{MAP_REL} is stale: run `python -m tests.build_map` and commit the result", file=sys.stderr)
            return 1
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"wrote {MAP_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
